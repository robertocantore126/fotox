// Fotox — albero completo dei menu.
// Formato voce: { label, short, a, chk, dis, sub }
//   short  scorciatoia mostrata a destra
//   a      azione eseguita al click (vedi js/actions.js)
//   chk    chiave di stato: se attiva, la voce mostra il segno di spunta
//   dis    voce disabilitata (grigia, non cliccabile)
//   sub    array di voci del sottomenu
// L'ordine dei menu e dei comandi segue la convenzione dell'editor di
// riferimento (Photoshop / Photopea), le etichette sono in inglese.

