// Fotox — which menu actions the app really implements (M7-T09, D-061).
//
// Scans the engine and shell sources for action ids ("layer:merge") and the
// native UI modules for the dialogs they run, and writes
// `js/data/implemented.js`. In the app, a menu item whose action is not in
// that list is greyed out ("Planned"), never a dead end. `check-data.mjs`
// fails when the file is stale.
//
// Usage:  node tools/gen-implemented.mjs [--check]

import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ui = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(ui, "..");

function files(dir, ext) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) out.push(...files(path, ext));
    else if (name.endsWith(ext)) out.push(path);
  }
  return out;
}

export function scan() {
  const ids = new Set();
  // Engine and shell: every quoted "prefix:name" literal.
  for (const dir of ["crates/fx-engine/src", "crates/fx-app/src"]) {
    for (const file of files(join(repo, dir), ".rs")) {
      for (const m of readFileSync(file, "utf8").matchAll(/"([a-z][a-z0-9-]*:[a-z0-9-]+)"/g)) ids.add(m[1]);
    }
  }
  // Native UI dialogs: `id === "x"` predicates and the modules' dialog tables.
  for (const file of files(join(ui, "js/native"), ".js")) {
    const src = readFileSync(file, "utf8");
    for (const m of src.matchAll(/id === "([a-z0-9-]+)"/g)) ids.add("dlg:" + m[1]);
  }
  // The live style dialogs (styles.js EFFECTS keys).
  for (const m of readFileSync(join(ui, "js/native/styles.js"), "utf8").matchAll(/^  "(style-[a-z0-9-]+)": \{/gm)) ids.add("dlg:" + m[1]);
  // Filter dialogs the engine previews (filters.js FILTERS keys).
  const filters = readFileSync(join(ui, "js/native/filters.js"), "utf8");
  const table = /const FILTERS = \{([\s\S]*?)\n\};/.exec(filters);
  if (table) for (const m of table[1].matchAll(/^  "([a-z0-9-]+)":/gm)) ids.add("dlg:" + m[1]);
  // Families the engine handles by prefix, written "prefix:*".
  for (const dir of ["crates/fx-engine/src"]) {
    for (const file of files(join(repo, dir), ".rs")) {
      for (const m of readFileSync(file, "utf8").matchAll(/starts_with\("(align|dist):"\)/g)) ids.add(m[1] + ":*");
      for (const m of readFileSync(file, "utf8").matchAll(/strip_prefix\("([a-z-]+:[a-z-]+:)"\)/g)) ids.add(m[1] + "*");
    }
  }
  // Viewport tools the engine builds (M8-T10): `"id" => Some(Box::new(…))`
  // in the tool registries, written "tool:<id>" (placeholders excluded).
  for (const file of files(join(repo, "crates/fx-engine/src/tools"), ".rs")) {
    for (const line of readFileSync(file, "utf8").split("\n")) {
      if (!line.includes("=> Some(Box::new(") || line.includes("NotYet")) continue;
      const head = line.split("=>")[0];
      for (const m of head.matchAll(/"([a-z][a-z0-9-]*)"/g)) ids.add("tool:" + m[1]);
    }
  }
  // actions.js's own native branches.
  const actions = readFileSync(join(ui, "js/actions.js"), "utf8");
  for (const m of actions.matchAll(/"(dlg:[a-z0-9-]+)"/g)) ids.add(m[1]);
  return [...ids].sort();
}

const body = (list) => `// Generated by ui/tools/gen-implemented.mjs — do not edit (M7-T09).
// The actions the app implements; other menu items are greyed out in the app.
export const IMPLEMENTED = new Set(${JSON.stringify(list, null, 2)});
`;

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const target = join(ui, "js/data/implemented.js");
  const text = body(scan());
  if (process.argv.includes("--check")) {
    const current = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
    if (current !== text) {
      console.error("js/data/implemented.js is stale: run node ui/tools/gen-implemented.mjs");
      process.exit(1);
    }
  } else {
    writeFileSync(target, text);
    console.log(`implemented.js: ${scan().length} actions`);
  }
}

export { body };
